'use strict';
// Run: node tests/flyer-editor-menu.test.cjs
// Verifies the production source structure and the actual collapse helper.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','site','index.html'),'utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)];
assert.ok(scripts.length>=3,'Main UI and Cloud scripts remain present');
for(const [,source] of scripts)new Function(source); // compile source, never run the app
const main=scripts[0][1];
const navStart=main.indexOf('const NAV_ITEMS=['),navEnd=main.indexOf('const previewFieldLabels=',navStart);
assert.ok(navStart>=0&&navEnd>navStart,'Navigation definition present');
const menus=new Function(main.slice(navStart,navEnd)+';return NAV_ITEMS;')();
assert.deepEqual(menus.map(item=>item[0]),['campaign','cards','bulk','review','backup'],'All five menus remain');
assert.equal(menus.find(item=>item[0]==='cards')[2].length,0,'Remove duplicated pinned Front Side/Back Side submenu');
assert.equal(menus.find(item=>item[0]==='campaign')[2].length,3,'Keep campaign editing choices');
assert.ok(html.includes('<button id="front" aria-pressed="true">Front</button>'),'Original working Front control retained');
assert.ok(html.includes('<button id="back" aria-pressed="false">Back</button>'),'Original working Back control retained');
assert.ok(main.includes("nav.append($('sidebarActions'))"),'Layout & Appearance joins the single-column main menu');
assert.ok(main.includes("$('sidebarContent').prepend(subnav)"),'Secondary choices moved to scrollable editor area');
assert.ok(main.includes('if(subnav)subnav.hidden='),'Empty secondary choices hidden');
assert.match(html,/#studioNav\{grid-template-columns:minmax\(0,1fr\)!important/,'Always one column');
assert.match(html,/#sidebarFixed\.menuCollapsed #editorMenuHint,#sidebarFixed\.menuCollapsed #studioNav\{display:none!important\}/,'Collapse only navigation and its hint');
const begin=main.indexOf('function initEditorMenuCollapse(){'),end=main.indexOf('function initStudioUI(){',begin);
assert.ok(begin>=0&&end>begin,'Menu collapse helper present');
const props={};
const classes=new Set();
const fixed={classList:{toggle(key,active){if(active)classes.add(key);else classes.delete(key)}}};
const toggle={setAttribute(key,value){props[key]=value},set textContent(value){props.text=value},set onclick(fn){props.click=fn}};
const nodes={sidebarFixed:fixed,editorMenuToggle:toggle};
const store={};
const localStorage={getItem(key){return store[key]??null},setItem(key,value){store[key]=value}};
const init=new Function('$','localStorage',main.slice(begin,end)+';return initEditorMenuCollapse;')(key=>nodes[key],localStorage);
init();
assert.equal(props['aria-expanded'],'true','Starts expanded for new users');
assert.equal(classes.has('menuCollapsed'),false,'Expanded menu shows main navigation');
props.click();
assert.equal(props['aria-expanded'],'false','Collapse exposes aria state');
assert.equal(props['aria-label'],'Expand editor menu','Collapse has accessible name');
assert.ok(classes.has('menuCollapsed'),'Collapse applies CSS state');
assert.equal(store['flyer-studio-editor-menu-collapsed'],'1','Collapse preference saved');
props.click();
assert.equal(props['aria-expanded'],'true','Menu expands on second click');
assert.equal(store['flyer-studio-editor-menu-collapsed'],'0','Expanded preference saved');
store['flyer-studio-editor-menu-collapsed']='1';
init();
assert.equal(props['aria-expanded'],'false','Collapsed state restores after reload');
console.log('PASS: editor navigation, single column, no duplicate tabs, accessible collapse and persistence.');
